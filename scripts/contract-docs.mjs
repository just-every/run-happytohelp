#!/usr/bin/env node
import {readFile,writeFile} from 'node:fs/promises'
import {parseContract} from '../src/site/base/seed-contract.mjs'

// CONTRACT.md alone owns clauses, acceptance points, status and evidence. The
// notes retain the earlier command requirements and explicitly open holds.
const command=process.argv[2]
if(!['write','check'].includes(command))throw Error('Usage: node scripts/contract-docs.mjs write|check')
const source=await readFile('CONTRACT.md','utf8'),contract=parseContract(source)
const lines=source.split('\n'),notes=await readFile('docs/acceptance-notes.md','utf8')
const notice='<!-- Generated by node scripts/contract-docs.mjs write. Edit CONTRACT.md, not this file. -->'
const tableHeader='| Clause | Title | Kind | Status | Evidence | Gap |\n| --- | --- | --- | --- | --- | --- |'
const rows=contract.clauses.map(clause=>lines[clause.row-1])
const summary='| Done | Partial | Missing | Total |\n| ---: | ---: | ---: | ---: |\n'+`| ${contract.counts.done} | ${contract.counts.partial} | ${contract.counts.missing} | ${contract.counts.total} |`
const acceptance=[notice,'# HappyToHelp acceptance',
 'Generated from [CONTRACT.md](CONTRACT.md). A cited journey is implementation evidence, not a fresh execution, deployment or live-provider qualification. The contract retains each qualification gap.',
 '## Requirements and acceptance',
 ...contract.clauses.map(clause=>`### ${clause.id} — ${clause.title}\n\n${clause.text}`),
 '## Evidence and status',summary,tableHeader+'\n'+rows.join('\n'),
 notes.trimEnd().replace(/^# Retained acceptance boundaries\n/,'## Retained acceptance boundaries\n')].join('\n\n')+'\n'
const claims=[notice,'# HappyToHelp implementation claims',
 'Generated from [CONTRACT.md](../CONTRACT.md). “Done” records implementation evidence only. The Evidence and Gap columns retain their original qualification limits.',
 summary,tableHeader+'\n'+rows.join('\n')].join('\n\n')+'\n'
for(const [path,expected] of [['ACCEPTANCE.md',acceptance],['docs/CLAIMS.md',claims]]){
 if(command==='write')await writeFile(path,expected)
 else if(await readFile(path,'utf8')!==expected)throw Error(`${path} is stale; run node scripts/contract-docs.mjs write`)
}
console.log(`Contract documents ${command==='write'?'generated':'current'} (${contract.clauses.length} clauses).`)
