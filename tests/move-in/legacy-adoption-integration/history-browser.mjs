import assert from 'node:assert/strict'
/** Called from the existing real package browser journey after queued completion. */
export async function historyBrowserFlow({page,runtime,source,inspect}){
 const returnTo=page.url()
 await page.goto(`${runtime.origin}/projects/${source}/conversations/synthetic-conversation`)
 await page.getByText('Historical private note retained in its original voice.',{exact:true}).waitFor()
 const collapsed=page.getByRole('button',{name:'Expand conversation history',exact:true})
 assert.ok(await collapsed.count()>0,'note-only older groups retain an expand control')
 assert.ok((await collapsed.first().boundingBox()).height>=44,'new historical group control has a 44px target')
 assert.ok(await collapsed.first().innerText().then(s=>s.includes('private note')))
 await collapsed.first().scrollIntoViewIfNeeded()
 await inspect('history-collapsed')
 while(await collapsed.count())await collapsed.first().press('Enter')
 await page.getByText('Historical escalation in the original thread.',{exact:true}).waitFor()
 await page.getByText('Historical note-only thread with its original author.',{exact:true}).waitFor()
 assert.ok(await page.getByText('Former staff',{exact:true}).count()>0)
 await page.getByText('Historical note-only thread with its original author.',{exact:true}).scrollIntoViewIfNeeded()
 await inspect('history-expanded')
 const ticket=page.getByRole('tab',{name:'Ticket',exact:true}),toggle=page.getByRole('button',{name:'Show conversation panel',exact:true})
 if(!await ticket.isVisible())await toggle.click()
 await ticket.click()
 await page.getByText('Historical assignee: Retired billing manager',{exact:true}).waitFor()
 await page.getByRole('button',{name:'Assign conversation. Current assignment: Unassigned',exact:true}).click()
 const menu=page.getByRole('menu')
 assert.equal(await menu.getByText('Retired billing manager',{exact:true}).count(),0)
 assert.equal(await menu.getByText('Historical support lead',{exact:true}).count(),0)
 await page.getByRole('button',{name:'Assign conversation. Current assignment: Unassigned',exact:true}).press('Escape')
 await ticket.focus();await page.mouse.move(0,0)
 await page.getByRole('tooltip').waitFor({state:'hidden'})
 await inspect('history-assignment')
 await page.goto(`${runtime.origin}/projects/${source}/macros`)
 await page.getByText('Retired billing manager (historical)',{exact:true}).waitFor()
 await inspect('history-macro-origin')
 await page.goto(returnTo)
 await page.getByText(/^complete · verified$/).waitFor()
}
